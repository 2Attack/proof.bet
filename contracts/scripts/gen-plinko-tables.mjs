#!/usr/bin/env node
/**
 * Generates src/generated/PlinkoTables.sol from packages/shared/src/tables/plinko-tables.json.
 * Run: node scripts/gen-plinko-tables.mjs
 *
 * The generated library embeds all ×100 multipliers as pure bytecode constants
 * (no SLOAD) to protect the VRF callback gas budget.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tablesPath = join(here, "..", "..", "packages", "shared", "src", "tables", "plinko-tables.json");
const outDir = join(here, "..", "src", "generated");
const outPath = join(outDir, "PlinkoTables.sol");

mkdirSync(outDir, { recursive: true });

/** @type {Record<string, Record<string, number[]>>} */
const tables = JSON.parse(readFileSync(tablesPath, "utf8"));

const ROWS = [8, 9, 10, 11, 12, 13, 14, 15, 16];
const RISKS = ["low", "medium", "high"]; // index = Risk enum ordinal

// Build inline function body for slotMultiplierX100
// We use nested if-else on rows then risk then slot to embed all values as literals.
// This avoids any storage access.

function buildLookup() {
  const lines = [];
  lines.push("        // Nested lookup — pure bytecode, no SLOAD.");

  for (let ri = 0; ri < ROWS.length; ri++) {
    const r = ROWS[ri];
    const rowData = tables[String(r)];
    const cond = ri === 0 ? "if" : "} else if";
    lines.push(`        ${cond} (rows == ${r}) {`);
    for (let riskIdx = 0; riskIdx < RISKS.length; riskIdx++) {
      const riskName = RISKS[riskIdx];
      const mults = rowData[riskName];
      const riskCond = riskIdx === 0 ? "if" : "} else if";
      lines.push(`            ${riskCond} (risk == Risk.${riskIdx === 0 ? "Low" : riskIdx === 1 ? "Medium" : "High"}) {`);
      lines.push(`                // slots 0..${mults.length - 1}`);
      // Use an inline array return for clarity
      const multsArr = mults.join(", ");
      // Build [uint256(x), uint256(y), ...] for all elements
      const multsLiteral = mults.map((v, i) => i === 0 ? `uint256(${v})` : `${v}`).join(", ");
      lines.push(`                uint256[${mults.length}] memory t = [${multsLiteral}];`);
      lines.push(`                require(slot < ${mults.length}, "PlinkoTables: slot OOB");`);
      lines.push(`                return t[slot];`);
    }
    lines.push(`            }`);
  }
  lines.push(`        }`);
  return lines.join("\n");
}

function buildMaxLookup() {
  const lines = [];
  lines.push("        // Nested lookup for max multiplier — pure bytecode, no SLOAD.");

  for (let ri = 0; ri < ROWS.length; ri++) {
    const r = ROWS[ri];
    const rowData = tables[String(r)];
    const cond = ri === 0 ? "if" : "} else if";
    lines.push(`        ${cond} (rows == ${r}) {`);
    for (let riskIdx = 0; riskIdx < RISKS.length; riskIdx++) {
      const riskName = RISKS[riskIdx];
      const mults = rowData[riskName];
      // For symmetric tables the max is always at index 0 (edge bucket), but compute it to be safe.
      const maxMult = Math.max(...mults);
      const riskCond = riskIdx === 0 ? "if" : "} else if";
      lines.push(`            ${riskCond} (risk == Risk.${riskIdx === 0 ? "Low" : riskIdx === 1 ? "Medium" : "High"}) {`);
      lines.push(`                return ${maxMult};`);
    }
    lines.push(`            }`);
  }
  lines.push(`        }`);
  return lines.join("\n");
}

const lookup = buildLookup();
const maxLookup = buildMaxLookup();

const sol = `// SPDX-License-Identifier: MIT
// AUTO-GENERATED by contracts/scripts/gen-plinko-tables.mjs — do not edit by hand.
// Source: packages/shared/src/tables/plinko-tables.json
pragma solidity 0.8.24;

import { Risk } from "../IProofBet.sol";

/// @title PlinkoTables
/// @notice Immutable Plinko payout lookup.  All values are multiplier×100 integers.
///         Embeds every table as bytecode constants — no storage reads, safe inside
///         the VRF callback.
///         rows: 8..16 inclusive.  Risk: Low=0, Medium=1, High=2.
library PlinkoTables {
    /// @notice Return the ×100 multiplier for a given (rows, risk, slot) triple.
    /// @param rows   Number of Plinko peg rows (8..16).
    /// @param risk   Risk tier.
    /// @param slot   Ball landing slot (0..rows, popcount of the path bits).
    function slotMultiplierX100(uint8 rows, Risk risk, uint256 slot) internal pure returns (uint256) {
${lookup}
        revert("PlinkoTables: invalid rows");
    }

    /// @notice Return the maximum ×100 multiplier for a given (rows, risk) pair.
    ///         This is the worst-case payout per unit stake — used by maxBet().
    function maxMultiplierX100(uint8 rows, Risk risk) internal pure returns (uint256) {
${maxLookup}
        revert("PlinkoTables: invalid rows");
    }
}
`;

writeFileSync(outPath, sol, "utf8");
console.log(`Generated ${outPath}`);

// Sanity check: count entries
let count = 0;
for (const r of ROWS) {
  for (const risk of RISKS) {
    count += tables[String(r)][risk].length;
  }
}
console.log(`Embedded ${count} multiplier entries across ${ROWS.length * RISKS.length} tables.`);
